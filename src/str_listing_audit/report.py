"""Markdown report generation from an AuditResult."""
from __future__ import annotations

from .audit import AuditResult

_ICON = {"error": "❌", "warning": "⚠️", "info": "ℹ️"}


def to_markdown(result: AuditResult) -> str:
    lines = [
        f"# Listing audit — {result.title}",
        "",
        f"- Listing ID: {result.listing_id}",
        f"- **Overall score: {result.score}/100**",
        f"- Errors: {len(result.by_severity('error'))} · "
        f"Warnings: {len(result.by_severity('warning'))} · "
        f"Infos: {len(result.by_severity('info'))}",
        "",
        "## Scores by category",
        "",
    ]
    for category, score in result.category_scores.items():
        lines.append(f"- {category}: {score}/100")
    lines += ["", "## Findings (evidence-only)", ""]
    if not result.findings:
        lines.append("No findings. Every checked field was present and within limits.")
    for f in result.findings:
        lines.append(f"- {_ICON.get(f.severity, '')} **[{f.category}]** {f.message} — evidence: `{f.evidence}`")
    lines += [
        "",
        "---",
        "Generated by str-listing-audit. Only values present in the input are reported; "
        "anything absent is marked UNVERIFIED, never invented.",
        "",
    ]
    return "\n".join(lines)
